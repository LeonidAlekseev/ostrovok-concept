export type ScenarioId = 'sea' | 'weekend' | 'europe'

export interface Destination {
  id: string
  name: string
  /** The name in the genitive: «от центра Праги». */
  genitive: string
  country: string
  lat: number
  lon: number
  /** Minimal demo price per night, ₽. */
  priceFrom: number
  scenarios: ScenarioId[]
  /** Show a marker for the destination on the hero globe. */
  onGlobe?: boolean
  /** Real metro stations of a city with a metro; the demo hotels get one of them as the nearest. */
  metro?: string[]
  /**
   * The city's hotels are real, from an Ostrovok search loaded by `npm run db:seed:valencia`: the catalogue
   * generator makes none for it.
   */
  real?: true
}

